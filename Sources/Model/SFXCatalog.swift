/// 効果音パネルの分類(タブ)
enum SFXCategory: String, CaseIterable, Identifiable {
    case transition, telop, variety, crowd, sparkle, impact, daily, food, town, nature, animal, season, game, horror, sports, jingle

    var id: String { rawValue }

    var title: String {
        switch self {
        case .transition: return String(localized: "切り替え")
        case .telop: return String(localized: "テロップ・UI")
        case .variety: return String(localized: "バラエティ")
        case .crowd: return String(localized: "歓声・反応")
        case .sparkle: return String(localized: "キラキラ")
        case .impact: return String(localized: "衝撃・アクション")
        case .daily: return String(localized: "日常")
        case .food: return String(localized: "料理・食事")
        case .town: return String(localized: "乗り物・街")
        case .nature: return String(localized: "自然・天気")
        case .animal: return String(localized: "動物")
        case .season: return String(localized: "季節・和")
        case .game: return String(localized: "ゲーム")
        case .horror: return String(localized: "ホラー・ミステリー")
        case .sports: return String(localized: "スポーツ・イベント")
        case .jingle: return String(localized: "ジングル")
        }
    }
}

